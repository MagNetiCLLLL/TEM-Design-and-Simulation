"""Presentation-only selection of declared electron-optical material.

This classifies existing meshes; it does not infer a field from a CAD shape or
change transport/occlusion. Zero excitation still leaves an optical component.
Profiles, canonical component identities and builder-owned region names are
used instead of display labels, colours, dimensions or ``mechanical_only``.
"""
from collections.abc import Mapping
import re

from temsim import component_keys as keys
from temsim.component_representation import non_material_role
from temsim.mechanical_profiles import DEFLECTOR_COIL_PROFILES


OPTICAL_VISIBILITY_HELP = (
    "Show source and electrodes, magnetic poles / coils / yokes, apertures, "
    "specimen / cell context, and detector receiving regions. Hide housings, "
    "vacuum tubes, supports and insulation. This is a display filter, independent "
    "of current excitation or insertion, and does not disable their effects in "
    "calculations. Existing schematic optical envelopes remain controlled by "
    "Schematic envelopes. Unclassified custom / imported bodies are hidden; "
    "their material shape alone does not establish an optical function."
)

_PASSIVE_PROFILES = frozenset({
    "magnetic_lens_housing", "post_projector_detector_chamber", "vacuum_liner",
    "vacuum_bore", "transverse_goniometer", "side_entry_sample_holder",
    "branch_reference_plane", "eftem_output_reference_plane", "virtual_plane",
    "virtual_layout", "integrated_magnetic_lens_channel",
})
_MAGNETIC_PROFILES = frozenset({
    "magnetic_pole_piece", "magnetic_excitation_coil", "magnetic_lens_yoke",
    "magnetic_lens_assembly", "c1_c2_pole_piece_cartridge", "magnetic_stigmator",
    "magnetic_quadrupole", "magnetic_hexapole", "magnetic_deflector",
    "quadrupole_field_channel", "tapered_sector_prism",
    "energy_filter_multipole_carrier", *DEFLECTOR_COIL_PROFILES,
})
_ELECTRODE_PROFILES = frozenset({
    "electrostatic_parallel_plates", "electrostatic_quadrupole",
    "electrostatic_camera_deflector", "fast_electrostatic_shutter",
    "electrostatic_bias_tube", "electrostatic_electrode_stack",
})
_APERTURE_PROFILES = frozenset({
    "circular_aperture", "fixed_differential_pumping_aperture",
    "two_blade_energy_slit", "xo_energy_slit_assembly",
})
_DETECTOR_PROFILES = frozenset({"retractable_detector_plane", "camera_sensor_plane"})
_GUN_KEYS = frozenset({
    keys.FEG_TIP, keys.FEG_EXTRACTOR, keys.FEG_ELECTROSTATIC_LENS,
    keys.FEG_ACCELERATOR, keys.FEG_DEFLECTOR, keys.FEG_STIGMATOR,
    keys.FEG_MONOCHROMATOR_WIEN, keys.FEG_MONOCHROMATOR_SLIT,
    *keys.THERMIONIC_GUN_COMPONENT_KEYS,
})
_COLUMN_KEYS = frozenset({
    *keys.CONDENSER_LENS_KEYS, *keys.PROBE_CORRECTOR_KEYS,
    *keys.IMAGE_CORRECTOR_KEYS, *keys.APERTURE_KEYS,
    keys.CONDENSER_DEFLECTOR, keys.BEAM_DEFLECTOR, keys.AC_DEFLECTOR,
    keys.CONDENSER_STIGMATOR, keys.OBJECTIVE_STIGMATOR,
    keys.IMAGE_DIFFRACTION_DEFLECTOR, keys.DIFFRACTION_STIGMATOR,
    keys.MINI_CONDENSER, keys.OBJECTIVE_LENS, keys.DIFFRACTION_LENS,
    keys.INTERMEDIATE_LENS, keys.PROJECTOR_LENS_1, keys.PROJECTOR_LENS_2,
    keys.NANOPULSER_DEFLECTOR, *keys.STEM_DETECTOR_KEYS,
    keys.FLUORESCENT_SCREEN, keys.CAMERA, "sample",
})

# These names are generated by the native material builders, not parsed from
# user-facing names. A foreign STEP solid called "coil" gains no such meaning.
_MAGNETIC_REGION = re.compile(
    r"(?:body|upper|lower|return_yoke|pole_(?:positive|negative|\d+)|"
    r"pole_pin_\d+|coil_\d+|(?:coil_\d+_)?[xy]_winding_[12])\Z"
)
_ELECTRODE_REGION = re.compile(r"(?:body|electrode_(?:\d+|positive|negative))\Z")
_APERTURE_REGION = frozenset({"body", "blade_positive", "blade_negative"})


def _data(part):
    if isinstance(part, Mapping):
        return part
    row = getattr(part, "data", None)
    return row if isinstance(row, Mapping) else {}


def _declared_field_host(key, parts_by_key):
    """A material host may be mechanical-only while its channel drives a field."""
    if not key or not parts_by_key:
        return False
    return any(_data(part).get("physical_host_key") == key
               for part in parts_by_key.values())


def optical_mesh_visible(mesh, part, *, parts_by_key=None) -> bool:
    """Whether an existing material region belongs in the optical-only view.

    ``part`` accepts a captured AssemblyPart or a TOML row. Unclassified STEP
    solids and custom mechanical additions are deliberately excluded, even if
    their label resembles a lens. The full view remains available unchanged.
    """
    row = _data(part)
    if not row:
        return False
    key = str(row.get("key", getattr(part, "key", "")))
    profile = str(row.get("mechanical_profile", ""))
    role = str(row.get("mechanical_part_role", ""))
    region = str(getattr(mesh, "region", ""))
    if non_material_role(row) or row.get("virtual_only"):
        return False
    if profile in _PASSIVE_PROFILES or role.startswith("custom_"):
        return False
    if row.get("model_3d", {}).get("base", {}).get("kind") == "step":
        # STEP import retains positioning, not per-solid functional annotation.
        return False
    if row.get("cell_context"):
        # Retain membrane/fluid context and its explicitly labelled specimen
        # reference; their original solid/wireframe semantics are unchanged.
        return True
    if getattr(mesh, "wireframe", False):
        return False
    if profile == "transverse_eds_detector_array":
        return re.fullmatch(r"segment_\d+_sensor", region) is not None
    if profile == "zebra_eels_detector":
        return re.fullmatch(r"active_strip_\d+(?:_scintillator)?", region) is not None
    if "stage_centers_z_mm" in row or profile == "electrostatic_electrode_stack":
        return re.fullmatch(r"electrode_\d+", region) is not None
    if profile in _APERTURE_PROFILES or key in keys.APERTURE_KEYS:
        return region in _APERTURE_REGION
    if row.get("aperture_plate_form") == "perforated_strip":
        return region in _APERTURE_REGION
    if profile in _DETECTOR_PROFILES:
        return region == "body"
    if profile in _ELECTRODE_PROFILES:
        return _ELECTRODE_REGION.fullmatch(region) is not None
    if profile in _MAGNETIC_PROFILES:
        return _MAGNETIC_REGION.fullmatch(region) is not None
    if (key in _GUN_KEYS or key in _COLUMN_KEYS
            or row.get("tip_particle_model") or row.get("tip_definition_file")):
        return (region in _APERTURE_REGION
                or _MAGNETIC_REGION.fullmatch(region) is not None
                or _ELECTRODE_REGION.fullmatch(region) is not None)
    # Explicit hardware binding permits known winding/pole region semantics on
    # otherwise unprofiled native hosts. An arbitrary bound body is insufficient.
    if _declared_field_host(key, parts_by_key):
        return region != "body" and _MAGNETIC_REGION.fullmatch(region) is not None
    return False
