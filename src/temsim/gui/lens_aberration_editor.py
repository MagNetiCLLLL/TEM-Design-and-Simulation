"""Transactional per-lens intrinsic coefficients; the field strengths stay fixed."""

from __future__ import annotations

from PySide6.QtCore import Qt, Signal
from PySide6.QtWidgets import (
    QDialog, QDialogButtonBox, QHeaderView, QLabel, QLineEdit,
    QTableWidget, QTableWidgetItem, QVBoxLayout,
)

from temsim.optics.intrinsic_aberrations import (
    INTRINSIC_TERMS, lens_intrinsic_coefficients, validated_coefficients,
)
from temsim.simulation_modes import mode_key, uses_field_maps


_NAMES = {
    "C1": "Intrinsic defocus", "A1": "Twofold astigmatism",
    "B2": "Axial coma", "A2": "Threefold astigmatism",
    "S3": "Star aberration", "A3": "Fourfold astigmatism",
    "C5": "Fifth-order spherical aberration", "A5": "Sixfold astigmatism",
}


def _label(text: str) -> QLabel:
    label = QLabel(text)
    label.setWordWrap(True)
    label.setTextInteractionFlags(Qt.TextInteractionFlag.TextSelectableByMouse)
    return label


class LensAberrationEditor(QDialog):
    """Edit a complete draft and replace only the selected lens on Apply."""

    applied = Signal()

    def __init__(self, state, lens, parent=None):
        super().__init__(parent)
        self.state = state
        self.lens_key = str(lens.key)
        self.setWindowTitle(f"Intrinsic aberrations — {lens.name}")
        self.resize(760, 650)
        self.explanation = _label(
            "Coefficients use this lens's local optical X–Y axes. Azimuth runs "
            "from local +X toward +Y. Enter additional intrinsic imperfections, "
            "not the residual aberrations of the complete instrument. Effects "
            "already generated by tilt, offset and corrector fields must not be "
            "entered again.\nCs and Cc remain in the existing lens controls. "
            "Applying these coefficients does not change lens excitation, "
            "polarity, position, or the existing Cs/Cc values."
        )
        self.model_note = _label("")
        self.table = QTableWidget(len(INTRINSIC_TERMS), 4)
        self.table.setHorizontalHeaderLabels(
            ("Term", "Meaning", "Coefficient (mm)", "Azimuth (deg)")
        )
        self.table.verticalHeader().hide()
        self.table.horizontalHeader().setSectionResizeMode(0, QHeaderView.ResizeMode.ResizeToContents)
        self.table.horizontalHeader().setSectionResizeMode(1, QHeaderView.ResizeMode.Stretch)
        self.table.setColumnWidth(2, 155)
        self.table.setColumnWidth(3, 120)
        self.editors = {}
        for row, term in enumerate(INTRINSIC_TERMS):
            for column, text in ((0, term.name), (1, _NAMES[term.name])):
                item = QTableWidgetItem(text)
                item.setFlags(item.flags() & ~Qt.ItemFlag.ItemIsEditable)
                self.table.setItem(row, column, item)
            for column, field in ((2, term.field), (3, term.azimuth_field)):
                if field is None:
                    item = QTableWidgetItem("—")
                    item.setFlags(item.flags() & ~Qt.ItemFlag.ItemIsEditable)
                    self.table.setItem(row, column, item)
                    continue
                editor = QLineEdit()
                editor.setObjectName(field)
                editor.setToolTip(
                    "Finite signed coefficient in millimetres; scientific notation is accepted."
                    if column == 2 else "Finite azimuth in degrees, in the lens-local optical frame."
                )
                self.editors[field] = editor
                self.table.setCellWidget(row, column, editor)
        self.convention = _label(
            "W = Σ Cₙₘ αⁿ⁺¹ cos[m(φ − φₙₘ)]/(n + 1); "
            "wave transfer exp(−i 2πW/λ), with α = q/f: lens-local transverse "
            "position divided by the current equivalent focal length. "
            "Zero means this additional term is "
            "omitted. Intrinsic C1 adds defocus without changing the magnetic "
            "excitation. Higher-order terms require adequate sampling."
        )
        self.status = _label("")
        self.buttons = QDialogButtonBox(
            QDialogButtonBox.StandardButton.Apply | QDialogButtonBox.StandardButton.Close
        )
        self.reset_button = self.buttons.addButton(
            "Reset draft to zero", QDialogButtonBox.ButtonRole.ResetRole
        )
        self.apply_button = self.buttons.button(QDialogButtonBox.StandardButton.Apply)
        self.apply_button.clicked.connect(self.apply_draft)
        self.buttons.rejected.connect(self.reject)
        self.reset_button.clicked.connect(self.reset_draft)
        layout = QVBoxLayout(self)
        for widget in (self.explanation, self.model_note, self.table,
                       self.convention, self.status, self.buttons):
            layout.addWidget(widget)
        self._set_draft(lens_intrinsic_coefficients(state, self.lens_key))
        self._refresh_model_note()

    def _refresh_model_note(self):
        descriptors = getattr(self.state, "lens_field_map_descriptors", {})
        bindings = getattr(self.state, "_lens_field_map_bindings", {})
        mapped = uses_field_maps(self.state) and (
            mode_key(self.state) in {"linear_geometry", "nonlinear_material"}
            or bool(descriptors.get(self.lens_key)) or self.lens_key in bindings
        )
        if mapped:
            self.model_note.setText(
                "This lens is configured to use a generated or imported field. "
                "When a matching field is active, native intrinsic terms are "
                "not added to that field, to avoid "
                "counting the same aberration twice. Values are retained for "
                "Ideal Optics / Analytical Field. A reported analytic fallback "
                "uses these coefficients."
            )
        else:
            self.model_note.setText(
                "Analytic lens model: particle and coherent propagation use "
                "the same applied intrinsic coefficients."
            )

    def _set_draft(self, values):
        for field, editor in self.editors.items():
            editor.setText(format(float(values.get(field, 0.0)), ".17g"))

    def reset_draft(self):
        self._set_draft({})
        self.status.setText("Draft reset. Click Apply to update this lens; Cs and Cc are unchanged.")

    def apply_draft(self) -> bool:
        try:
            coefficients = validated_coefficients(
                {field: float(editor.text()) for field, editor in self.editors.items()}
            )
            current = getattr(self.state, "lens_intrinsic_aberrations", {})
            updated = dict(current)
            if any(value != 0.0 for value in coefficients.values()):
                updated[self.lens_key] = coefficients
            else:
                updated.pop(self.lens_key, None)
        except (TypeError, ValueError, OverflowError) as exc:
            self.status.setText(f"Not applied: {exc}. The active lens is unchanged.")
            return False
        self.state.lens_intrinsic_aberrations = updated
        self._set_draft(coefficients)
        self._refresh_model_note()
        self.status.setText("Applied to this lens. Recalculate to update particles, waves and residual aberrations.")
        self.applied.emit()
        return True
